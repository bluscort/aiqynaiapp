export function retrieve(query: string, limit = 3): string[] {
  const q = query.toLowerCase();
  return KNOWLEDGE.map((chunk) => ({ chunk, score: chunk.tags.filter((tag) => q.includes(tag)).length }))
    .filter((x) => x.score > 0)
    .sort((a, b) => b.score - a.score)
    .slice(0, limit)
    .map((x) => x.chunk.text);
}
