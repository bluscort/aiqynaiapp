const LETTER = 'a-zа-яёәіңғүұқөһ0-9';

/** Whole-word match, so "NU" does not fire inside "kaznu" or "menu". */
function hasWord(q: string, word: string): boolean {
  const escaped = word.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  return new RegExp(`(^|[^${LETTER}])${escaped}($|[^${LETTER}])`).test(q);
}

function tryCutoffLookup(q: string, lang: Lang): string | null {
  if (!/(балл|бал |балы|пор|шекті|проход|өту|грант)/.test(q)) return null;
  const uni = UNIVERSITIES.find((u) => [u.short.ru, u.short.kk, u.id].some((w) => hasWord(q, w.toLowerCase())));
  if (!uni) return null;
  const gop = GOP_KEYWORDS.find(([re]) => re.test(q))?.[1];
  const matches = PROGRAMS.filter((p) => p.uniId === uni.id && (!gop || p.gop === gop));
  if (matches.length === 0) return null;
  const rows = matches
    .map((p) => `• ${p.gop} ${p.name[lang]}: ~${p.cutoff} ${lang === 'ru' ? '(сельская квота ~' : '(ауыл квотасы ~'}${p.ruralCutoff})`)
    .join('\n');
  return {
    ru: `**${uni.name.ru}** — ориентировочные проходные баллы на грант:\n\n${rows}\n\nЭто оценка по данным прошлых лет, а не гарантия. Открой **Матчер** (свайп влево), введи свой балл — я посчитаю шанс и соберу 4 комбинации ГОП.`,
    kk: `**${uni.name.kk}** — грантқа болжамды өту балдары:\n\n${rows}\n\nБұл өткен жылдар деректері бойынша бағалау, кепілдік емес. **Матчерді** аш (солға сырғыт), балыңды енгіз — мүмкіндігіңді есептеп, 4 ББТ комбинациясын құрастырамын.`,
  }[lang];
}

