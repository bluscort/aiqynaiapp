type Poly = [number, number, number];

function parseSide(side: string): Poly | null {
  const out: Poly = [0, 0, 0];
  const terms = side.replace(/\*/g, '').replace(/-/g, '+-').split('+').filter((t) => t.length > 0);
  if (terms.length === 0) return null;
  for (const term of terms) {
    let deg = 0;
    let coef = term;
    if (term.endsWith('x^2')) {
      deg = 2;
      coef = term.slice(0, -3);
    } else if (term.endsWith('x')) {
      deg = 1;
      coef = term.slice(0, -1);
    }
    const value = coef === '' ? 1 : coef === '-' ? -1 : Number(coef);
    if (!Number.isFinite(value)) return null;
    out[deg] += value;
  }
  return out;
}

function trySolveEquation(text: string, lang: Lang): string | null {
  const norm = text
    .toLowerCase()
    .replace(/[−–—]/g, '-')
    .replace(/²/g, '^2')
    .replace(/х/g, 'x') // Cyrillic "х" typed instead of Latin "x"
    .replace(/,/g, '.');
  const match = norm.match(/([0-9x.^*+\-\s]+)=([0-9x.^*+\-\s]+)/);
  if (!match || !match[0].includes('x')) return null;
  const left = parseSide(match[1]!.replace(/\s/g, ''));
  const right = parseSide(match[2]!.replace(/\s/g, ''));
  if (!left || !right) return null;

  const a = left[2] - right[2];
  const b = left[1] - right[1];
  const c = left[0] - right[0];
  const n = fmtNum;

  if (a === 0) {
    if (b === 0) return null;
    const x = -c / b;
    return {
      ru: `Решаем линейное уравнение по шагам:\n\n**1. Приводим к виду kx + m = 0**\n${n(b)}x ${c >= 0 ? '+' : '−'} ${n(Math.abs(c))} = 0\n\n**2. Переносим свободный член**\n${n(b)}x = ${n(-c)}\n\n**3. Делим на коэффициент при x**\nx = ${n(-c)} / ${n(b)} = **${n(x)}**\n\n**Проверка:** ${n(b)}·${n(x)} ${c >= 0 ? '+' : '−'} ${n(Math.abs(c))} = 0 ✓`,
      kk: `Сызықтық теңдеуді қадамдап шешеміз:\n\n**1. kx + m = 0 түріне келтіреміз**\n${n(b)}x ${c >= 0 ? '+' : '−'} ${n(Math.abs(c))} = 0\n\n**2. Бос мүшені көшіреміз**\n${n(b)}x = ${n(-c)}\n\n**3. x-тің коэффициентіне бөлеміз**\nx = ${n(-c)} / ${n(b)} = **${n(x)}**\n\n**Тексеру:** ${n(b)}·${n(x)} ${c >= 0 ? '+' : '−'} ${n(Math.abs(c))} = 0 ✓`,
    }[lang];
  }

  const d = b * b - 4 * a * c;
  const head: Bi = {
    ru: `Решаем квадратное уравнение по шагам:\n\n**1. Приводим к виду ax² + bx + c = 0**\na = ${n(a)}, b = ${n(b)}, c = ${n(c)}\n\n**2. Дискриминант**\nD = b² − 4ac = ${n(b * b)} − ${n(4 * a * c)} = ${n(d)}`,
    kk: `Квадрат теңдеуді қадамдап шешеміз:\n\n**1. ax² + bx + c = 0 түріне келтіреміз**\na = ${n(a)}, b = ${n(b)}, c = ${n(c)}\n\n**2. Дискриминант**\nD = b² − 4ac = ${n(b * b)} − ${n(4 * a * c)} = ${n(d)}`,
  };

  if (d < 0) {
    return head[lang] + {
      ru: `\n\n**3. Вывод**\nD < 0 — действительных корней нет.`,
      kk: `\n\n**3. Қорытынды**\nD < 0 — нақты түбірлері жоқ.`,
    }[lang];
  }
  if (d === 0) {
    const x = -b / (2 * a);
    return head[lang] + {
      ru: `\n\n**3. Корень**\nD = 0, значит один корень: x = −b / 2a = **${n(x)}**`,
      kk: `\n\n**3. Түбір**\nD = 0, яғни бір түбір: x = −b / 2a = **${n(x)}**`,
    }[lang];
  }
  const sq = Math.sqrt(d);
  const x1 = (-b + sq) / (2 * a);
  const x2 = (-b - sq) / (2 * a);
  const rootD = Number.isInteger(sq) ? n(sq) : `√${n(d)}`;
  return head[lang] + {
    ru: `\n\n**3. Корни**\nx₁ = (−b + √D) / 2a = (${n(-b)} + ${rootD}) / ${n(2 * a)} = **${n(x1)}**\nx₂ = (−b − √D) / 2a = (${n(-b)} − ${rootD}) / ${n(2 * a)} = **${n(x2)}**\n\n**Проверка по Виету:** x₁ + x₂ = ${n(x1 + x2)} = −b/a ✓, x₁·x₂ = ${n(x1 * x2)} = c/a ✓`,
    kk: `\n\n**3. Түбірлер**\nx₁ = (−b + √D) / 2a = (${n(-b)} + ${rootD}) / ${n(2 * a)} = **${n(x1)}**\nx₂ = (−b − √D) / 2a = (${n(-b)} − ${rootD}) / ${n(2 * a)} = **${n(x2)}**\n\n**Виет бойынша тексеру:** x₁ + x₂ = ${n(x1 + x2)} = −b/a ✓, x₁·x₂ = ${n(x1 * x2)} = c/a ✓`,
  }[lang];
}

// ── Arithmetic (recursive-descent parser, no eval) ───────────────────────

function evaluate(expr: string): number | null {
  let pos = 0;
  const peek = () => expr[pos];
  const parseNumber = (): number | null => {
    const m = expr.slice(pos).match(/^\d+(\.\d+)?/);
    if (!m) return null;
    pos += m[0].length;
    return Number(m[0]);
  };
  const parseFactor = (): number | null => {
    if (peek() === '-') {
      pos++;
      const v = parseFactor();
      return v === null ? null : -v;
    }
    let base: number | null;
    if (peek() === '(') {
      pos++;
      base = parseExpr();
      if (peek() !== ')') return null;
      pos++;
    } else {
      base = parseNumber();
    }
    if (base === null) return null;
    if (peek() === '^') {
      pos++;
      const exp = parseFactor();
      return exp === null ? null : Math.pow(base, exp);
    }
    return base;
  };
  const parseTerm = (): number | null => {
    let v = parseFactor();
    while (v !== null && (peek() === '*' || peek() === '/')) {
      const op = expr[pos++];
      const r = parseFactor();
      if (r === null || (op === '/' && r === 0)) return null;
      v = op === '*' ? v * r : v / r;
    }
    return v;
  };
  const parseExpr = (): number | null => {
    let v = parseTerm();
    while (v !== null && (peek() === '+' || peek() === '-')) {
      const op = expr[pos++];
      const r = parseTerm();
      if (r === null) return null;
      v = op === '+' ? v + r : v - r;
    }
    return v;
  };
  const result = parseExpr();
  return pos === expr.length ? result : null;
}

function tryArithmetic(text: string, lang: Lang): string | null {
  const prefix = text.match(/^[^\d(−-]*/)?.[0] ?? '';
  // Only treat the message as arithmetic if it is short or an explicit "calculate" request,
  // so "Что нового в ЕНТ 2025-2026?" is not answered with −1.
  if (prefix.trim().length > 0 && !/(посчитай|вычисли|сколько будет|реши|есепте|шеш)/i.test(prefix)) return null;
  const cleaned = text
    .slice(prefix.length)
    .replace(/[?=\s]+$/, '')
    .replace(/[−–—]/g, '-')
    .replace(/[×·]/g, '*')
    .replace(/[÷:]/g, '/')
    .replace(/,/g, '.')
    .replace(/\s/g, '');
  if (!/^[\d.+\-*/()^]+$/.test(cleaned) || !/\d[+\-*/^]/.test(cleaned)) return null;
  const value = evaluate(cleaned);
  if (value === null || !Number.isFinite(value)) return null;
  return {
    ru: `Считаем с учётом порядка действий (скобки → степени → × и ÷ → + и −):\n\n${cleaned} = **${fmtNum(value)}**`,
    kk: `Амалдардың ретін сақтап есептейміз (жақша → дәреже → × пен ÷ → + пен −):\n\n${cleaned} = **${fmtNum(value)}**`,
  }[lang];
}

